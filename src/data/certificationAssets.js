function titleFromPath(file) {
  const filename = file.split("/").at(-1);
  return filename
    .replace(/\.(png|jpe?g|webp|pdf)$/i, "")
    .replace(/\.png$/i, "")
    .replace(/\.jpg$/i, "")
    .replace(/_/g, " ")
    .replace(/-/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function providerFromPath(file) {
  const parts = file.split("/");
  return parts.length > 3 ? parts[2] : "Featured Courses";
}

export const certificationAssets = certificationFiles.map((file, index) => {
  const eliteOverride = eliteFiles.get(file);
  const title = eliteOverride ? eliteOverride.title : titleFromPath(file);
  const provider = eliteOverride ? eliteOverride.provider : providerFromPath(file);
  const category = eliteOverride ? eliteOverride.category : providerFromPath(file);
  const isProctored = !!(eliteOverride && eliteOverride.proctored);

  return {
    id: `cert-${String(index + 1).padStart(3, "0")}`,
    title,
    provider,
    category,
    date: isProctored ? "Official Proctored Exam" : "Continuous Learning Course",
    src: `/${file}`,
    type: file.toLowerCase().endsWith(".pdf") ? "pdf" : "image",
    alt: `${title} certificate proof`,
    caption: `${title} credential proof from ${provider}.`,
    featured: isProctored,
    proctored: isProctored,
    priority: isProctored
  };
});

