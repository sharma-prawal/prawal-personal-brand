// Who issued each course. Folders name the platform; loose files are mapped by name.
const folderProviders = {
  LinkedIn: "LinkedIn Learning",
  HackerRank: "HackerRank",
  MongoDB: "MongoDB University",
  GraphQL: "Apollo GraphQL"
};
const fileProviders = [
  [/^AWS Partner/, "AWS Training and Certification"],
  [/^Claude/, "Anthropic"],
  [/Node\.js and Express|JavaScript Promises/, "Pluralsight"],
  [/Docker Essentials|Machine Learning with Python/, "IBM Cognitive Class"],
  [/GitOps/, "Codefresh"],
  [/.*/, "Udemy"]
];

function providerFromPath(file) {
  const parts = file.split("/");
  if (folderProviders[parts[2]]) return folderProviders[parts[2]];
  return fileProviders.find(([pattern]) => pattern.test(parts.at(-1)))[1];
}

function courseTitle(file) {
  const name = file.split("/").at(-1);
  if (courseTitles[name]) return courseTitles[name];
  const title = titleFromPath(file);
  // HackerRank skill badges: "SQL Advanced" -> "SQL (Advanced)"
  if (file.includes("/HackerRank/")) return title.replace(/ (Basic|Intermediate|Advanced)$/, " ($1)");
  // MongoDB University course codes: "M001 MongoDB Basics" -> "M001: MongoDB Basics"
  if (file.includes("/MongoDB/")) return title.replace(/^([AM]\d+\w*) /, "$1: ");
  return title;
}

export const certificationAssets = certificationFiles.map((file, index) => {
  const eliteOverride = eliteFiles.get(file);
  const title = eliteOverride ? eliteOverride.title : courseTitle(file);
  const provider = eliteOverride ? eliteOverride.provider : providerFromPath(file);
  const category = eliteOverride ? eliteOverride.category : providerFromPath(file);
  const isProctored = !!(eliteOverride && eliteOverride.proctored);

  return {
    id: `cert-${String(index + 1).padStart(3, "0")}`,
    title,
    provider,
    category,
    date: isProctored ? "Official Proctored Exam" : "Continuous Learning Course",
    src: `/${file}`,
    type: file.toLowerCase().endsWith(".pdf") ? "pdf" : "image",
    alt: `${title} certificate issued to Prawal Sharma`,
    caption: isProctored ? `${title}, issued by ${provider}.` : `${title}, a course certificate from ${provider}.`,
    featured: isProctored,
    proctored: isProctored,
    priority: isProctored
  };
});

